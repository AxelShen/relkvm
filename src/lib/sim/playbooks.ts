export function blankCustom(from?: Playbook): Playbook {
  const id = `custom-${Date.now()}`;
  if (from) {
    return {
      ...from,
      id,
      name: `${from.name} (custom)`,
      nameZh: `${from.nameZh}（自訂）`,
      steps: from.steps.map((s, i) => ({ ...s, id: `${id}-s${i}` })),
      custom: true,
    };
  }
  return {
    id,
    name: "Custom RELEASE",
    nameZh: "新流程",
    blurb: "自訂 BIOS / Shell / OS 步驟。",
    stages: ["POST", "BIOS"],
    custom: true,
    steps: [
      { id: `${id}-s0`, tool: "power", action: "cycle", label: "循環電源" },
      {
        id: `${id}-s1`,
        tool: "wait",
        label: "等待 POST 提示",
        needle: "Press DEL",
        timeoutMs: 10000,
      },
    ],
  };
}

