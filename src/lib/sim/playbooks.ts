const k = (id: string, label: string, key: string): Playbook["steps"][number] => ({
  id,
  tool: "key",
  label,
  key,
});
const t = (id: string, label: string, text: string): Playbook["steps"][number] => ({
  id,
  tool: "type",
  label,
  text,
  submit: true,
});
const w = (id: string, label: string, needle: string, timeoutMs = 9000): Playbook["steps"][number] => ({
  id,
  tool: "wait",
  label,
  needle,
  timeoutMs,
});
const a = (id: string, label: string, needle: string): Playbook["steps"][number] => ({
  id,
  tool: "assert",
  label,
  needle,
});

